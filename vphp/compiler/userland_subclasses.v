module compiler

import compiler.linker
import compiler.repr
import os

pub const userland_classes_header = '<?php\n// Generated by VPHP.\n'

struct UserlandSubclass {
	name        string
	parent      string
	trait_name  string
	min_version int
}

fn userland_type_name(name string) string {
	return name.replace('\\\\', '\\').trim_string_left('\\')
}

fn collect_userland_subclasses(elements []repr.PhpRepr, type_versions map[string]int) ![]UserlandSubclass {
	mut declared := map[string]bool{}
	for element in elements {
		name := match element {
			repr.PhpClassRepr { element.php_name }
			repr.PhpEnumRepr { element.php_name }
			repr.PhpInterfaceRepr { element.php_name }
			else { continue }
		}
		declared[userland_type_name(name).to_lower()] = true
	}
	mut classes := map[string]UserlandSubclass{}
	mut dependencies := []repr.PhpRepr{}
	for entry in elements {
		if entry !is repr.PhpClassRepr {
			continue
		}
		element := match entry {
			repr.PhpClassRepr { entry }
			else { continue }
		}
		spec := element.userland_subclass or { continue }
		if !element.is_native_trait {
			return error('PhpUserlandSubclass requires a PhpExportTrait declaration on ${element.name}')
		}
		name := userland_type_name(spec.name)
		parent := userland_type_name(spec.parent)
		trait_name := userland_type_name(element.php_name)
		if !valid_php_export_name(name) || !valid_php_export_name(parent)
			|| !valid_php_export_name(trait_name) {
			return error('PhpUserlandSubclass on ${element.php_name} requires valid PHP class and parent names')
		}
		key := name.to_lower()
		if declared[key] {
			return error('duplicate exported PHP type name `${name}`')
		}
		declared[key] = true
		classes[key] = UserlandSubclass{name, parent, trait_name, element.min_php_version}
		dependencies << repr.PhpClassRepr{
			php_name: name
			parent:   parent
		}
	}
	mut ordered := []UserlandSubclass{cap: classes.len}
	mut versions := type_versions.clone()
	for element in linker.registration_order(dependencies)! {
		entry := match element {
			repr.PhpClassRepr { element }
			else { return error('unexpected registration type for userland subclass') }
		}
		key := entry.php_name.to_lower()
		mut cls := classes[key]
		parent_version := versions[cls.parent.to_lower()]
		if parent_version > cls.min_version {
			cls = UserlandSubclass{ ...cls, min_version: parent_version }
		}
		versions[key] = cls.min_version
		ordered << cls
	}
	return ordered
}

// userland_class_declarations appends namespaced PHP class bodies to a stub or
// a standalone PHP file loaded after the extension and the project autoloader.
pub fn (c &Compiler) userland_class_declarations() string {
	mut blocks := []string{}
	for cls in c.userland_subclasses {
		namespace := if cls.name.contains('\\') { ' ' + cls.name.all_before_last('\\') } else { '' }
		short_name := cls.name.all_after_last('\\')
		mut declaration := [
			'    class ${short_name} extends \\${cls.parent}',
			'    {',
			'        use \\${cls.trait_name};',
			'    }',
		]
		if cls.min_version > 0 {
			declaration = [
				'    if (PHP_VERSION_ID >= ${cls.min_version}) {',
				...declaration.map('    ' + it),
				'    }',
			]
		}
		blocks << ['namespace${namespace} {', ...declaration, '}'].join('\n')
	}
	return blocks.join('\n\n')
}

pub fn remove_stale_userland_classes(path string) ! {
	if os.is_file(path) && !os.is_link(path) {
		if (os.read_file(path)!).starts_with(userland_classes_header) {
			os.rm(path)!
		}
	}
}
